import { useCallback, useMemo, useRef } from 'react'
import type { UIMessage } from '@ai-sdk/react'
import { useChat } from '@ai-sdk/react'
import { useToast } from '@opengovsg/design-system-react'
import { DefaultChatTransport } from 'ai'

import {
  AiBuilderOutput,
  useAiBuilderContext,
} from '@/pages/AiBuilder/AiBuilderContext'
import { MAX_MESSAGES } from '@/pages/AiBuilder/constants'
import {
  deduplicateMessages,
  extractTextContent,
  extractWorkflowToolResult,
  transformMessages,
} from '@/pages/AiBuilder/helpers'

export interface Message {
  id: string // this is auto-generated by the AI SDK
  text: string
  traceId?: string // only assistant messages have this
  isUser: boolean
  /**
   * Whether this message contains a workflow tool call result.
   * Used to determine where to show the preview button on mobile.
   */
  hasWorkflow: boolean
}

// Custom message type with metadata
export type CustomUIMessage = UIMessage<{
  traceId?: string
}>

export interface UseChatStreamOptions {
  initialMessages?: Message[]
}

export function useChatStream(options: UseChatStreamOptions) {
  const toast = useToast()
  const {
    ddSessionId,
    output: currentOutput,
    setChatInput,
    setChatMessages,
    setOutput,
    setFlowName,
    setIsToolCalling,
  } = useAiBuilderContext()

  // Use ref for currentOutput to avoid stale closure in onFinish
  const outputRef = useRef(currentOutput)
  outputRef.current = currentOutput

  // Use ref to always access the latest initialMessages in callbacks.
  // useChat captures its transport/onFinish on mount, so without a ref,
  // prepareSendMessagesRequest and onFinish would use stale initialMessages
  // (e.g. the old 50 messages after clicking "New Chat").
  const initialMessagesRef = useRef(options?.initialMessages)
  initialMessagesRef.current = options?.initialMessages

  const {
    messages: aiMessages,
    sendMessage,
    setMessages,
    status,
    error: aiError,
    stop,
  } = useChat<CustomUIMessage>({
    transport: new DefaultChatTransport({
      api: '/api/chat',
      credentials: 'include',
      prepareSendMessagesRequest: ({ messages }) => {
        // Filter out any initialMessages already tracked by the AI SDK to avoid
        // duplicates (the SDK accumulates messages across exchanges in its own state)
        const aiMessageIds = new Set(messages.map((m) => m.id))
        const initialMsgs = (initialMessagesRef.current || [])
          .filter((msg) => !aiMessageIds.has(msg.id))
          .map((msg) => ({
            id: msg.id,
            role: msg.isUser ? 'user' : 'assistant',
            parts: [{ type: 'text', text: msg.text }],
            ...(msg.traceId && { metadata: { traceId: msg.traceId } }),
          }))

        // Prepend initial messages to maintain full conversation context.
        // Filter out assistant messages with no text content — these can be left
        // behind when the user stops the stream before any output is produced,
        // and would fail backend schema validation.
        const allMessages = [...initialMsgs, ...messages].filter((msg) => {
          if (msg.role !== 'assistant') {
            return true
          }
          return (msg.parts ?? []).some(
            (part) =>
              part.type === 'text' &&
              !!(part as { type: string; text?: string }).text?.trim(),
          )
        })

        const body = {
          messages: allMessages,
          sessionId: ddSessionId,
        }
        return { body }
      },
    }),
    onData: (dataPart) => {
      console.log(`dataPart: ${Date.now()}`, dataPart)
    },
    onToolCall: () => {
      console.log(`onToolCall: ${Date.now()}`)
      setIsToolCalling(true)
    },
    onError: (error: Error) => {
      toast({
        title: 'Error: ' + error.message,
        status: 'error',
        duration: 3000,
        isClosable: true,
        position: 'top',
      })
      setIsToolCalling(false)
    },
    onFinish: ({ messages, isAbort }) => {
      setIsToolCalling(false)
      if (isAbort) {
        return
      }

      const transformedMessages = transformMessages(messages)

      // Combine initial messages with new messages to preserve full history
      const allMessages = deduplicateMessages([
        ...(initialMessagesRef.current || []),
        ...transformedMessages,
      ])

      // Check if the last message contains a workflow tool result
      const lastMessage = messages[messages.length - 1]
      const workflowResult = extractWorkflowToolResult(lastMessage) as
        | (AiBuilderOutput & { name?: string })
        | null

      const outputToUse = workflowResult || outputRef.current

      setChatInput(allMessages[allMessages.length - 1].text)
      setChatMessages(allMessages)

      if (outputToUse) {
        setOutput(outputToUse)
      }
      if (workflowResult?.name) {
        setFlowName(workflowResult.name || 'Build with AI')
      }
    },
  })

  // Transform AI SDK messages to our Message format.
  // Uses options?.initialMessages directly (not the ref) so the memo re-runs
  // reactively when initialMessages changes (e.g., after "New Chat").
  const messages = useMemo<Message[]>(() => {
    const isActivelyStreaming = status === 'streaming' || status === 'submitted'
    const initialMsgs = options?.initialMessages || []

    // Filter user and assistant messages from AI SDK
    let messagesToTransform = aiMessages.filter(
      (msg) => msg.role === 'user' || msg.role === 'assistant',
    )

    // If streaming, exclude the last assistant message (shown via currentResponse)
    if (isActivelyStreaming && messagesToTransform.length > 0) {
      const lastMsg = messagesToTransform[messagesToTransform.length - 1]
      if (lastMsg.role === 'assistant') {
        messagesToTransform = messagesToTransform.slice(0, -1)
      }
    }

    // Filter out assistant messages with no text content — these are left behind
    // when the user stops the stream before any output is produced
    messagesToTransform = messagesToTransform.filter(
      (msg) =>
        msg.role !== 'assistant' || extractTextContent(msg).trim().length > 0,
    )

    const transformedMessages = transformMessages(messagesToTransform)
    const combined = deduplicateMessages([
      ...initialMsgs,
      ...transformedMessages,
    ])

    // Ensure only the last message with hasWorkflow: true keeps the flag
    let lastReadyIndex = -1
    const allMessages = combined.map((msg, index) => {
      if (msg.hasWorkflow) {
        lastReadyIndex = index
      }
      return { ...msg, hasWorkflow: false }
    })

    if (lastReadyIndex !== -1) {
      allMessages[lastReadyIndex].hasWorkflow = true
    }

    return allMessages
  }, [aiMessages, options?.initialMessages, status])

  // Get the current streaming response (last assistant message that's still being streamed)
  const currentResponse = useMemo(() => {
    const isActivelyStreaming = status === 'streaming' || status === 'submitted'

    if (!isActivelyStreaming) {
      return ''
    }

    const lastMessage = aiMessages[aiMessages.length - 1]
    if (lastMessage && lastMessage.role === 'assistant') {
      return extractTextContent(lastMessage)
    }
    return ''
  }, [aiMessages, status])

  const resetChat = useCallback(() => {
    setMessages([])
  }, [setMessages])

  // Wrapper for sendMessage that matches the expected signature
  const sendMessageWrapper = useCallback(
    (userPrompt: string) => {
      sendMessage({
        role: 'user',
        parts: [{ type: 'text', text: userPrompt }],
      })
    },
    [sendMessage],
  )

  return {
    messages,
    currentResponse,
    isStreaming: status === 'submitted' || status === 'streaming',
    error: aiError?.message || null,
    sendMessage: sendMessageWrapper,
    cancelStream: stop,
    resetChat,
    hasReachedLimit: messages.length >= MAX_MESSAGES,
  }
}
